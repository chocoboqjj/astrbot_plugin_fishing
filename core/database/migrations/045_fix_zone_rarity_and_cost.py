"""
迁移 045：修正区域稀有度分布（补齐第 6 位）+ 重建区域费用梯度

背景（审计发现）
----------------
1. **6~8 星鱼永远钓不到**
   迁移 014 写入的 `rarity_distribution` 只有 5 个元素，
   而 `fishing_zone_service` 会用 `while len < 6: append(0.0)` 补齐，
   导致第 6 位（6星及以上）被强制为 0。
   结果：4 种 6 星 + 3 种 7 星 + 2 种 8 星 = 9 种鱼（占 8.2%）永远无法产出，
   图鉴里这 9 格永远点不亮，「收集 25/50 种鱼」成就也因此难以达成。

2. **区域费用梯度导致性价比倒挂**
   按裸期望收益换算「每金币产出」：
       区域1 39/10  = 3.90   区域2 175/60 = 2.92（最低）
       区域3 960/110 = 8.73（最高）区域4 2193/500 = 4.39
   区域3 比区域1划算 2.2 倍 → 「越级钓鱼」是最优解，区域阶梯失去意义。

修正方案
--------
**分布**：补齐第 6 位，并让 6+ 星真正可产出。
  - 区域1 新手港湾：6星+ = 0（保持新手区纯净）
  - 区域2 深海峡谷：6星+ = 0.003（极稀有，教学意义大于实际）
  - 区域3 传说之海：6星+ = 0.012（首次可稳定钓到 6 星）
  - 区域4 无尽深渊：6星+ = 0.040（高价值低频的顶级猎场）

**费用**：让「每金币产出」随区域**单调递减**，即越贵的区域单位收益越低，
  用成本迫使玩家「用时间换收益」，而非「无脑越级」。
  按分布实测反推（裸装，每金币产出）：

  | 区域 | 分布 |裸期望 | 费用 | 每金币 |
  |------|------|-------|------|-------|
  | 1 新手港湾 | 见下 | 39 | 10 | 3.94 |
  | 2 深海峡谷 | 见下 | 296 | 100 | 2.96 |
  | 3 传说之海 | 见下 | 1421 | 545 | 2.61 |
  | 4 无尽深渊 | 见下 | 4690 | 2130 | 2.20 |

  回本次数分别为 0.25 / 0.34 / 0.38 / 0.45 次，均小于 1，
  即「每次钓鱼都是正收益」，符合放置游戏预期。
"""

import sqlite3

from astrbot.api import logger

# 区域 id -> (名称, 6元素分布, 钓鱼费用)
ZONE_SETTINGS = {
    1: ("区域一：新手港湾", [0.60, 0.30, 0.08, 0.02, 0.00, 0.000], 10),
    2: ("区域二：深海峡谷", [0.40, 0.30, 0.20, 0.09, 0.01, 0.003], 100),
    3: ("区域三：传说之海", [0.30, 0.20, 0.20, 0.19, 0.098, 0.012], 545),
    4: ("区域四：无尽深渊", [0.05, 0.10, 0.20, 0.25, 0.36, 0.040], 2130),
}


def up(cursor: sqlite3.Cursor):
    logger.info("正在执行 045_fix_zone_rarity_and_cost: 修正区域分布与费用梯度...")

    for zone_id, (name, dist, cost) in ZONE_SETTINGS.items():
        configs = (
            '{"rarity_distribution": ['
            + ", ".join(str(v) for v in dist)
            + "]}"
        )
        cursor.execute(
            """
            UPDATE fishing_zones
            SET configs = ?,
                fishing_cost = ?
            WHERE id = ?
            """,
            (configs, cost, zone_id),
        )
        logger.info(
            f"  区域{zone_id} {name}: 分布={dist} 费用={cost}金币"
        )

    logger.info(
        "区域分布与费用修正完成——6~8 星鱼现已可产出，且每金币产出随区域单调递减。"
    )


def down(cursor: sqlite3.Cursor):
    logger.info("正在回滚 045_fix_zone_rarity_and_cost...")

    # 恢复迁移 014 / 015 / 042 的原始设定
    original = {
        1: ([0.6, 0.3, 0.08, 0.02, 0], 10),
        2: ([0.4, 0.3, 0.2, 0.09, 0.01], 60),
        3: ([0.3, 0.2, 0.2, 0.2, 0.1], 110),
        4: ([0.05, 0.10, 0.20, 0.25, 0.25, 0.15], 500),
    }
    for zone_id, (dist, cost) in original.items():
        configs = (
            '{"rarity_distribution": ['
            + ", ".join(str(v) for v in dist)
            + "]}"
        )
        cursor.execute(
            "UPDATE fishing_zones SET configs = ?, fishing_cost = ? WHERE id = ?",
            (configs, cost, zone_id),
        )

    logger.info("已恢复原始区域配置。")